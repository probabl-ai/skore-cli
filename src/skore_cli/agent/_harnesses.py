"""Harness registry, detection and per-harness configuration writers.

Each :class:`Harness` knows how to (best-effort) *detect* whether it is present and
how to *configure* it so it talks to the Skore Hub agent's OpenAI-compatible
endpoint. The writers deliberately differ because harnesses are configured very
differently (project file vs. global file vs. env vars vs. a translation proxy).

Credentials stay user-managed: the API key is never written to a file, only
*referenced* (``{env:...}`` for opencode, ``$SKORE_HUB_API_KEY`` in env files,
``${{ env.SKORE_HUB_API_KEY }}`` for Continue). Interactive device-flow tokens are
refreshed on the fly and emitted as a bearer.
"""

from __future__ import annotations

import json
import os
import shutil
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from skore_cli._skore import auth as _auth
from skore_cli._style import console

API_KEY_ENV = "SKORE_HUB_API_KEY"
DEFAULT_HUB_URL = "http://127.0.0.1:8000"
DEFAULT_MODEL_ID = "skore-agent"

# Marker recording what `skore agent init` configured, so `status` is trivial.
MARKER_FILENAME = ".skore-agent.json"

# Visible connection file written by the generic harness (paste-friendly).
GENERIC_CONFIG_FILENAME = "skore-agent.json"

# Header naming the hub workspace the agent is attached to (a workspace public id).
WORKSPACE_HEADER = "X-Skore-Workspace"

# opencode provider name: no dots (avoids the opencode option-dropping bug #5674).
OPENCODE_PROVIDER_KEY = "skore"
OPENCODE_SCHEMA = "https://opencode.ai/config.json"
SESSION_HEADER = "X-Skore-Session-Id"
SESSION_PLUGIN_FILENAME = "skore-session.js"
SESSION_PLUGIN_SOURCE = f"""\
// Auto-generated by `skore agent init`. Forwards opencode's session id to the
// Skore Hub agent so the hub can resume the matching conversation history.
export const SkoreSession = async () => ({{
  "chat.headers": async (input, output) => {{
    const id = input?.provider?.info?.id ?? input?.provider?.id;
    if (id === "{OPENCODE_PROVIDER_KEY}" && input?.sessionID) {{
      output.headers["{SESSION_HEADER}"] = input.sessionID;
    }}
  }},
}});
"""


def base_url(hub_url: str) -> str:
    """Return the OpenAI-compatible base URL the harness should point at."""
    return f"{hub_url.rstrip('/')}/v1"


@dataclass(frozen=True)
class Credential:
    """A resolved hub credential.

    ``kind`` is ``"api_key"`` (user-managed via ``SKORE_HUB_API_KEY``, never
    embedded), ``"bearer"`` (an interactive device-flow access token, embedded as
    a literal) or ``"none"``.
    """

    kind: str
    token: str = ""


def resolve_credential() -> Credential:
    """Resolve the hub credential, mirroring the Python authentication.

    Prefers the user-managed API key (referenced, never stored); otherwise
    refreshes the persisted interactive token (relaunching the device login if the
    refresh token is dead) and returns it as a bearer.
    """
    if os.environ.get(API_KEY_ENV):
        return Credential("api_key")

    token = _auth("token").fresh_token(relogin=True)
    if token and token.get("access_token"):
        return Credential("bearer", token["access_token"])
    return Credential("none")


def header_pair(cred: Credential) -> tuple[str, str] | None:
    """Return the ``(name, value)`` auth header, opencode/generic ``{env:}`` style."""
    if cred.kind == "api_key":
        return ("X-API-Key", f"{{env:{API_KEY_ENV}}}")
    if cred.kind == "bearer":
        return ("Authorization", f"Bearer {cred.token}")
    return None


def workspace_headers(ctx: ConfigureContext) -> dict[str, str]:
    """Return the workspace-attachment header, if a workspace slug is set.

    API-key credentials are already bound to a workspace server-side, so the
    header is only meaningful (and only written) for the interactive bearer path.
    """
    if ctx.hub_workspace:
        return {WORKSPACE_HEADER: ctx.hub_workspace}
    return {}


def fetch_workspaces(hub_url: str, cred: Credential) -> list[tuple[str, str]]:
    """List the workspaces the user can attach to, as ``(public_id, name)`` pairs.

    Calls the hub ``GET /identity/workspaces`` with the resolved credential. Used
    only by the interactive bearer picker; API-key auth needs no selection.
    """
    import httpx

    if cred.kind == "api_key":
        token = os.environ.get(API_KEY_ENV, "")
        headers = {"X-API-Key": token}
    elif cred.kind == "bearer":
        headers = {"Authorization": f"Bearer {cred.token}"}
    else:
        headers = {}

    url = f"{hub_url.rstrip('/')}/identity/workspaces"
    response = httpx.get(url, headers=headers, timeout=30, follow_redirects=True)
    response.raise_for_status()
    payload = response.json()
    items = payload.get("items", payload) if isinstance(payload, dict) else payload

    workspaces: list[tuple[str, str]] = []
    for item in items or []:
        public_id = item.get("public_id") or item.get("slug")
        if not public_id:
            continue
        workspaces.append((public_id, item.get("name") or public_id))
    return workspaces


@dataclass
class ConfigureContext:
    """Inputs shared by every harness writer."""

    workspace: Path
    hub_url: str
    model_id: str
    cred: Credential
    # Hub workspace slug (public id) the agent is attached to; only written for
    # the bearer path (API keys are already workspace-bound server-side).
    hub_workspace: str | None = None
    # opencode-only:
    write_session_plugin: bool = True
    # generic-only:
    write_file: bool = True

    @property
    def base_url(self) -> str:
        return base_url(self.hub_url)


def _no_credential_note() -> None:
    console.print(
        f"  [skore.muted](no credential resolved -- set {API_KEY_ENV} or run "
        "`skore hub login`, then re-run init)[/]"
    )


def _warn_workspace_header_unsupported(ctx: ConfigureContext) -> None:
    """Warn when a bearer setup cannot carry the workspace header.

    This harness cannot send custom headers, so an interactive-login (bearer)
    token cannot be scoped to a workspace and the hub now rejects unscoped agent
    calls. A workspace-scoped API key carries the binding intrinsically.
    """
    if ctx.cred.kind == "bearer":
        console.print(
            f"[yellow]  This harness cannot send the {WORKSPACE_HEADER} header, so "
            "an interactive-login token cannot be scoped to a workspace and the "
            f"hub will reject the call. Use a workspace-scoped API key "
            f"({API_KEY_ENV}) instead.[/]"
        )


