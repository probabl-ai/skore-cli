@dataclass(frozen=True)
class Harness:
    """A configurable agent harness."""

    name: str
    label: str
    detect: Callable[[Path], bool]
    configure: Callable[[ConfigureContext], dict[str, Any]]
    session_binding: str = "fallback"  # "plugin" | "fallback"
    extras: tuple[str, ...] = field(default=())


HARNESSES: dict[str, Harness] = {
    "opencode": Harness(
        "opencode",
        "opencode  -  project config + session binding (turnkey)",
        _detect_opencode,
        _configure_opencode,
        session_binding="plugin",
    ),
    "copilot": Harness(
        "copilot",
        "GitHub Copilot CLI  -  sourceable env file",
        _detect_copilot,
        _configure_copilot,
    ),
    "continue": Harness(
        "continue",
        "Continue  -  global ~/.continue/config.yaml",
        _detect_continue,
        _configure_continue,
    ),
    "cline": Harness(
        "cline",
        "Cline  -  VS Code settings (best-effort; paste key in panel)",
        _detect_cline,
        _configure_cline,
    ),
    "claude-code": Harness(
        "claude-code",
        "Claude Code  -  LiteLLM proxy config (experimental)",
        _detect_claude_code,
        _configure_claude_code,
    ),
    "generic": Harness(
        "generic",
        "generic  -  print values for any OpenAI-compatible client",
        _detect_never,
        _configure_generic,
    ),
}

HARNESS_NAMES = list(HARNESSES)


def detect_harnesses(workspace: Path) -> list[str]:
    """Return the names of harnesses that look present, in registry order."""
    return [
        name
        for name, harness in HARNESSES.items()
        if name != "generic" and harness.detect(workspace)
    ]
